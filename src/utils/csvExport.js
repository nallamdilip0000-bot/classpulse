/**
 * CSV Export Utility for ClassPulse
 * 
 * Complies with educational reporting privacy:
 * - Sanitizes strings and escapes commas/quotes
 * - Excludes private teacher staff notes from student performance exports by default
 * - Stamps generation timestamp and filter scope
 */

export function exportToCSV({
  filename = 'classpulse_export.csv',
  title = 'ClassPulse Academic Support Report',
  columns = [],
  data = [],
  metadata = {}
}) {
  const lines = [];

  // Metadata headers
  lines.push(`"${title.replace(/"/g, '""')}"`);
  lines.push(`"Generated On: ${new Date().toLocaleString()}"`);
  if (metadata.filterDescription) {
    lines.push(`"Filters Applied: ${metadata.filterDescription.replace(/"/g, '""')}"`);
  }
  if (metadata.author) {
    lines.push(`"Generated By: ${metadata.author.replace(/"/g, '""')}"`);
  }
  lines.push(`"Note: Demo export contains fictional synthetic data for demonstration purposes."`);
  lines.push(''); // blank row separator

  // Column Headers
  const headerRow = columns.map(col => `"${(col.label || col.key).replace(/"/g, '""')}"`).join(',');
  lines.push(headerRow);

  // Data Rows
  for (const row of data) {
    const rowValues = columns.map(col => {
      let val = row[col.key];
      if (typeof col.format === 'function') {
        val = col.format(val, row);
      }
      if (val === null || val === undefined) {
        return '""';
      }
      // If array or object, stringify
      if (typeof val === 'object') {
        val = JSON.stringify(val);
      }
      val = String(val).replace(/"/g, '""');
      return `"${val}"`;
    });
    lines.push(rowValues.join(','));
  }

  const csvContent = lines.join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
